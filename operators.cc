#include<iostream>

int main() {
    int a=5,b=2;

    std::cout << "a + b = " << (a + b) << "\na - b = " << (a - b) << std::endl;
    std::cout << "a * b = " << (a * b) << "\na / b = " << (a / b) << std::endl;
    std::cout << "a % b = " << (a % b) << std::endl;
    std::cout << "++a = " << ++a << std::endl;
    std::cout << "--a = " << --a << std::endl;

    return 0;
}
